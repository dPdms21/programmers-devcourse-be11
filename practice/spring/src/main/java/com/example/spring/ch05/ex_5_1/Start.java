// * 서비스 추상화란?
// 여러 가지 구체적인 방법(구현)들에서 '공통된 개념/동작'만 뽑아내, 그것을 하나의 일관된
// 인터페이스로 표현하는 것. 사용하는 쪽은 '무엇을 하는지'(추상)만 알고,
// '어떻게 하는지'(구체 구현)는 몰라도 되게 만듦

// * 왜 필요한가? (추상화가 없으면..)
// - 코드가 특정 기술/환경에 종속
// - 기술을 바꾸면 그 기술을 쓰는 코드를 전부 고쳐야함 (변경에 약함)
// - 외부 시스템에 묶여 테스트가 어렵고 느려짐

// * 서비스 추상화의 핵심 아이디어
//   '일관성 없는 여러 저수준 기술'을, '일관된 고수준 인터페이스' 뒤로 숨김
//   그리고 실제 구현은 DI로 갈아 끼움
//   -> 비즈니스 로직(애플리케이션 코드)은 추상화된 인터페이스에만 의존하므로,
//      기술이 바뀌어도(또는 테스트용 가짜로 바꿔도) 비즈니스 로직 코드는 그대로
//   이것은 1~4장에서 본 'IoC/DI', '전략 패턴', '예외 추상화'와 같은 원리의 연장선

// * 5장의 전개 (이 원리를 단계별로 적용)
// - ex_5_1 : 사용자 레벨 관리 기능 추가      (추상화를 적용할 '대상' 코드를 먼저 만듦)
// - ex_5_2 : 트랜잭션 서비스 추상화          (PlatformTransactionManager)
// - ex_5_3 : 서비스 추상화와 단일 책임 원칙   (비즈니스 로직 vs 트랜잭션 분리)
// - ex_5_4 : 메일 서비스 추상화             (MailSender + 테스트 대역)

// * 요구사항
// - 사용자 레벨 BASIC, SIVER, GOLD
// - 사용자 처음 가입하면 BASIC 후 활동에 따라 업그레이드
// - 가입 후 50회 이상 로그인하면 SILVER로 업그레이드
// - SILVER에서 30회 이상 GOLD로 업그레이드
// - 사용자 레벨의 변경 작업은 일정한 주기를 가지고 일괄적으로 진행
// 변경 작업 전에는 조건을 충족하더라도 레벨의 변경이 일어나지 않음

// * 이 예제의 구성 (책임에 따라 계층을 나눔)
