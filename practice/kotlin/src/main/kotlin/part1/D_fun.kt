// 4. 매개변수에 기본값 주기
fun addWithDefault(a: Int, b: Int = 10) = a + b

// 5. 세 수를 더하는 함수
// 함수 안에서 다른 함수를 부를 수 있음
fun addThree(a: Int, b: Int, c: Int) = add(add(a, b), c)

// 6. 이름은 같지만 자료형이 다른 함수 - 오버로딩
fun plus(a: Int, b: Int) = a + b
fun plus(a: Double, b: Double) = a + b
fun plus(a: String, b: String) = a + b

// ------------------------------------------------------------
// 예제 1. 함수 호출하기
// ------------------------------------------------------------
fun d_exam1() {
    // 함수 이름 뒤에 괄호를 쓰고, 그 안에 넘길 값(인자)을 적음
    val sum = add(10, 20)
    println("add(10, 20) = $sum")               // 30

    // 돌려받은 값은 그대로 다른 곳에 쓸 수 있음
    println("add(1, 2) = ${add(1, 2)}")         // 3
    println("add(3, 4) + 100 = ${add(3, 4) + 100}")   // 107

    // 변수를 인자로 넘길 수도 있음
    val x = 5
    val y = 7
    println("add(x, y) = ${add(x, y)}")         // 12

    // 한 번 만든 함수는 몇 번이든 다시 쓸 수 있음. 이것이 함수를 만드는 이유
    println(add(1, 1))                          // 2
    println(add(100, 200))                      // 300
    println(add(-5, 5))                         // 0

    println("add2(10, 20) = ${add2(10, 20)}")   // 30
}

// ------------------------------------------------------------
// 예제 2. 반환값이 없는 함수 호출하기
// ------------------------------------------------------------
fun d_exam2() {
    printSum(3, 4)                              // 3 + 4 = 7
    printSum2(5, 6)                             // 5 + 6 = 11

    // 값을 돌려주지 않으므로 결과를 변수에 담는 것은 의미가 없음
    val nothing = printSum(1, 1)
    println(nothing)                            // kotlin.Unit
}

// ------------------------------------------------------------
// 예제 3. 단일 표현식 함수 호출하기 - 모양만 다를 뿐 결과는 같음
// ------------------------------------------------------------
fun d_exam3() {
    println(add(2, 3))      // 5   중괄호 + return
    println(add2(2, 3))     // 5   중괄호 + return (한 줄)
    println(add3(2, 3))     // 5   =로 축약
    println(add4(2, 3))     // 5   =로 축약 + 반환 자료형 생략
}

// ------------------------------------------------------------
// 예제 4. 기본값이 있는 함수 호출하기
// ------------------------------------------------------------
fun d_exam4() {
    println(addWithDefault(5, 3))   // 8    b에 3을 넘김
    println(addWithDefault(5))      // 15   b를 생략 -> 기본값 10이 쓰임
}

// ------------------------------------------------------------
// 예제 5. 이름 붙인 인자 (Named Argument)
// ------------------------------------------------------------
fun d_exam5() {
    // 인자에 매개변수 이름을 붙여서 넘기면 무엇을 넘기는지 한눈에 보임
    println(add(a = 10, b = 20))    // 30

    // 이름을 붙이면 순서를 바꿔도 됨
    println(add(b = 20, a = 10))    // 30

    // 뒤쪽 매개변수만 골라서 넘길 때 특히 유용
    println(addWithDefault(a = 7))          // 17
    println(addWithDefault(b = 100, a = 7)) // 107
}

// ------------------------------------------------------------
// 예제 6. 함수 안에서 함수 부르기
// ------------------------------------------------------------
fun d_exam6() {
    println("addThree(1, 2, 3) = ${addThree(1, 2, 3)}")     // 6
