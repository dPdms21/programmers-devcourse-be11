}

// ------------------------------------------------------------
// 예제 7. 오버로딩 - 넘기는 자료형에 따라 알맞은 함수가 자동으로 선택됨
// ------------------------------------------------------------
fun d_exam7() {
    println(plus(1, 2))                 // 3        Int 버전
