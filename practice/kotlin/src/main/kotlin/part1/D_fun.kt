// 함수

// fun 함수이름([변수 이름]: 자료형, [변수 이름]: 자료형, ...): [반환값의 자료형] {
//  내용...
// }

// fun: 함수를 선언하겠다는 키워드
// 함수 이름: 소문자로 시작하는 카멜 표기법을 씀
// 매개변수: 코틀린의 매개변수는 val이라서 함수 안에서 값을 바꿀 수 없음
// 반환 자료형: 함수가 돌려줄 값의 자료형 콜론 뒤에 씀
// return: 값을 돌려주면서 함수를 종료

// 1. 가장 기본이 되는 덧셈 함수
fun add(a: Int, b: Int): Int {
    val result = a + b

    return result
}

fun add2(a: Int, b: Int): Int {
    return a + b
}

// 2. 반환값이 없는 함수 - Unit
// 값을 돌려주지 않고 출력만 하는 함수. 반환 자료형이 Unit
// Unit은 생략할 수 있음
fun printSum(a: Int, b: Int): Unit {
    println("sum of $a and $b is ${a + b}")
}

fun printSum2(a: Int, b: Int) {
    println("$a + $b = ${a + b}")
}

// 3. 단일 표현식 함수 - 중괄호와 return 생략하기
// 함수의 내용이 표현식 하나뿐이라면 중괄호 대신 등호(=)로 연결할 수 있음
fun add3(a: Int, b: Int): Int = a + b
// 게다가 반환 자료형도 컴파일러가 추론하므로 생략할 수 있음
fun add4(a: Int, b: Int) = a + b

// 주의! 중괄호 { }를 사용하는 함수는 반환 자료형을 생략할 수 없음. 추론해주지 않음
/*
