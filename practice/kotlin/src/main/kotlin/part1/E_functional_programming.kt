// 예제 5. 값에 의한 호출 vs 이름에 의한 호출
// ------------------------------------------------------------
fun e_exam5() {
    // 아래 람다식은 실행되는 순간 "람다식 실행!"을 출력
    // 이 출력이 '언제' 나오는지를 보면 두 방식의 차이를 알 수 있음
    val lambda: () -> Boolean = {
        println("  람다식 실행!")
        true
    }

    println("[값에 의한 호출]")
    println(callByValue(lambda()))
    // 출력 순서: 람다식 실행! -> callByValue 함수 시작 -> true
    // 인자 자리에서 lambda()를 먼저 계산해 true를 만든 뒤에 함수로 들어감

    println("[이름에 의한 호출]")
    println(callByName(lambda))
    // 출력 순서: callByName 함수 시작 -> 람다식 실행! -> true
    // 계산하지 않은 함수를 그대로 넘기고, 함수 안에서 b() 를 부를 때 비로소 계산됨

    // 즉 이름에 의한 호출은 '계산을 미룰 수 있다'는 것이 핵심
}

