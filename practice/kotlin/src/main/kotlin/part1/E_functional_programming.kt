// 예제 2. 람다식 - 이름 없는 함수를 변수에 담기
// ------------------------------------------------------------
fun e_exam2() {
    // 함수를 값처럼 변수에 담을 수 있음. 이것이 '함수가 일급 객체'라는 말의 뜻
    val square: (Int) -> Int = { x -> x * x }
    println(square(5))          // 25

    // 변수 자료형을 생략하면 람다식 안에 매개변수 자료형을 적어야 함
    val sumLambda = { a: Int, b: Int -> a + b }
    println(sumLambda(10, 20))  // 30

    // 반대로 변수 자료형을 적으면 람다식 쪽에서 자료형을 생략할 수 있음
    val sumLambda2: (Int, Int) -> Int = { a, b -> a + b }
    println(sumLambda2(10, 20)) // 30

    // 매개변수가 하나뿐이면 이름 대신 it을 쓸 수 있음
    val double: (Int) -> Int = { it * 2 }
    println(double(7))          // 14

    // 매개변수가 없는 람다식
    val hello: () -> Unit = { println("안녕하세요, 람다식입니다.") }
    hello()

    // 여러 줄짜리 람다식 - 마지막 줄이 곧 반환값 (return을 쓰지 않음)
    val calcArea: (Int, Int) -> Int = { w, h ->
        println("  가로 $w, 세로 $h 넓이를 구합니다.")
        w * h                   // 이 줄의 값이 반환됨
    }
    println(calcArea(3, 4))     // 12
}

