// 예제 4. 고차 함수 - 함수를 '반환'하기
// ------------------------------------------------------------
fun e_exam4() {
    val add10 = makeAdder(10)       // "10을 더하는 함수"를 만들어 받음
    val add100 = makeAdder(100)     // "100을 더하는 함수"를 만들어 받음

    println(add10(5))               // 15
    println(add10(20))              // 30
    println(add100(5))              // 105

    // 만들자마자 바로 호출할 수도 있음
    println(makeAdder(3)(4))        // 7
}

