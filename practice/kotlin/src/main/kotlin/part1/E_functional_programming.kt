    e_exam3()     // 고차 함수 - 함수를 인자로 넘기기
    e_exam4()     // 고차 함수 - 함수를 반환하기
    e_exam5()     // 값에 의한 호출 vs 이름에 의한 호출
    e_exam6()     // 람다식의 매개변수 다루기
}