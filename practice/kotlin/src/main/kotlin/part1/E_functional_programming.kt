package part1

// * 함수형 프로그래밍
// 순수 함수를 작성하여 프로그램의 부작용을 줄이는 프로그래밍 기법

// * 순수 함수
// 1) 같은 인자를 넣으면 항상 같은 결과가 나오고,
// 2) 함수 바깥의 값을 바꾸지 않는 (부작용이 없는) 함수를 말함
//    부작용(Side effect)은 함수가 결과를 돌려주는 일 말고 바깥에 끼치는 영향을 뜻함
// 예) 바깥 변수의 값을 바꾸기, 화면에 출력하기, 파일에 쓰기, 네트워크로 전송하기

// * 순수 함수가 아닌 함수
// 바깥 변수를 읽거나 바꾸는 함수, 호출할 때마다 결과가 달라지는 함수 등
// 부작용이 있으면 결과를 예측하기 어렵고, 테스트도 어려워짐

// * 람다식
// 다른 함수의 인자로 넘기는 함수, 함수의 결과값으로 반환하는 함수, 변수에 저장하는 함수를 말함
// - 이름 없이 만드는 함수: 중괄호로 감싸고, 화살표(->)를 기준으로 왼쪽은 매개변수, 오른쪽은 본문
// 본문의 마지막 줄이 그대로 반환값이 됨 (return을 쓰지 않음)

// * 일급 객체
// 1) 변수에 담을 수 있고, 2) 함수의 인자로 넘길 수 있고, 3) 함수의 반환값이 될 수 있는 대상
// 코틀린에서는 함수가 일급 객체. 그래서 함수를 값처럼 다룰 수 있음

// * 고차 함수
// 함수를 인자로 받거나, 함수를 반환하는 함수

// * 호출
// - 값에 의한 호출: 인자를 넘기기 '전에' 미리 계산해서, 그 결과값을 넘김. 코틀린 함수 호출의 기본 방식
// - 이름에 의한 호출: 계산하지 않은 채 함수(람다) 자체를 넘기고, 함수 안에서 실제로 쓸 때 계산
// - 참조에 의한 호출: 이미 만들어 둔 함수를 ::를 붙여 참조로 넘김   예) ::sumFun

// 순수 함수: 인자만 가지고 계산하고, 바깥에 아무런 영향을 주지 않음
fun pureAdd(a: Int, b: Int): Int = a + b

// 순수 함수가 아닌 함수: 바깥 변수 total을 바꿈
var total = 0

fun impureAdd(a: Int): Int {
    total += a
    return total
}

// 고차 함수 - 함수를 인자로 받는 함수
// operator: (Int, Int) -> Int: Int 두 개를 받아서 Int를 돌려주는 함수
fun calculate(a: Int, b: Int, operator: (Int, Int) -> Int): Int {
    return operator(a, b) // 넘겨받은 함수를 여기서 실행
}

// 고차 함수 - 함수를 반환하는 함수
// 반환 자료형이 "(Int) -> Int". 즉 함수를 돌려줌
fun makeAdder(n: Int): (Int) -> Int {
    return { x -> x + n } // n을 기억하는 새 함수를 만들어 돌려줌
}

// 참조로 넘기기 위한 보통 함수 (재료)
fun sumFun(a: Int, b: Int): Int = a + b
fun minusFun(a: Int, b: Int): Int = a - b

// 값에 의한 호출, 이름에 의한 호출
// 값에 의한 호출: Boolean '값'을 받음 -> 넘기기 전에 이미 계산이 끝나 있음
fun callByValue(b: Boolean): Boolean {
    println("  callByValue 함수 시작")

    return b
}

// 이름에 의한 호출: () -> Boolean, 즉 '함수'를 받음 -> 안에서 b()를 부를 때 비로소 계산됨
fun callByName(b: () -> Boolean): Boolean {
    println("  callByName 함수 시작")

    return b()
}

// ------------------------------------------------------------
// 예제 1. 순수 함수 vs 순수하지 않은 함수
// ------------------------------------------------------------
fun e_exam1() {
    // 순수 함수는 몇 번을 불러도 결과가 같음
    println(pureAdd(2, 3))      // 5
    println(pureAdd(2, 3))      // 5
    println(pureAdd(2, 3))      // 5

    // 순수하지 않은 함수는 같은 인자를 넣어도 결과가 계속 달라짐
    println(impureAdd(2))       // 2
    println(impureAdd(2))       // 4
    println(impureAdd(2))       // 6
    println("바깥 변수 total이 바뀌었다: $total")   // 6

    // 함수형 프로그래밍은 이런 부작용을 줄여서 결과를 예측 가능하게 만드는 것이 목표
}

