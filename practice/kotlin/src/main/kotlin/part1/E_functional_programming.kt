// 예제 6. 람다식의 매개변수 다루기
// ------------------------------------------------------------
fun e_exam6() {
    // 매개변수가 두 개 이상이면 it을 쓸 수 없음. 이름을 직접 지어야 함
    val multiply: (Int, Int) -> Int = { a, b -> a * b }
    println(multiply(3, 4))         // 12

    // 쓰지 않는 매개변수는 밑줄(_)로 표시할 수 있음
    val onlyFirst: (Int, Int) -> Int = { a, _ -> a }
    println(onlyFirst(10, 20))      // 10   두 번째 값은 무시됨

    // 람다식을 인자로 넘길 때도 it을 쓸 수 있음
    val nums = listOf(1, 2, 3, 4, 5)
    println(nums.map { it * 2 })            // [2, 4, 6, 8, 10]
    println(nums.filter { it % 2 == 0 })    // [2, 4]
    println(nums.sumOf { it })              // 15
    // map, filter 같은 코틀린 표준 함수들이 모두 고차 함수
    // 우리가 '무엇을 할지'만 람다식으로 넘기면 '어떻게 반복할지'는 알아서 처리해 줌
}

